"""Draw the home-page "signal" figure: dots (reports) that connect into a signal.

Writes _includes/signal.md, included by index.qmd. Deterministic: the same seed
always draws the same figure. Usage: python tools/design/make_signal.py
"""

from __future__ import annotations

import math
import random
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "_includes" / "signal.md"

WIDTH, HEIGHT = 560, 440
CENTRE = (300.0, 214.0)
SEED = 14  # Calvados
N_DOTS = 46
N_LINKS = 11
MIN_GAP = 34.0

CYAN, GREEN, NEUTRAL, INK = "#19a6e3", "#2bcf8c", "#b9cfdc", "#10283a"


def sample_dots(rng: random.Random) -> list[tuple[float, float]]:
    """Points spread inside an ellipse, apart from each other and from the centre."""
    dots: list[tuple[float, float]] = []
    tries = 0
    while len(dots) < N_DOTS and tries < 20000:
        tries += 1
        angle = rng.uniform(0, 2 * math.pi)
        radius = math.sqrt(rng.uniform(0.04, 1.0))
        x = 285 + radius * 245 * math.cos(angle)
        y = 220 + radius * 185 * math.sin(angle)
        if math.dist((x, y), CENTRE) < 48:
            continue
        if all(math.dist((x, y), d) >= MIN_GAP for d in dots):
            dots.append((x, y))
    return dots


def pick_linked(dots: list[tuple[float, float]]) -> list[tuple[float, float]]:
    """Dots spread around the centre, one per angular sector."""
    sectors: dict[int, tuple[float, float]] = {}
    for d in dots:
        angle = math.atan2(d[1] - CENTRE[1], d[0] - CENTRE[0]) % (2 * math.pi)
        sector = int(angle / (2 * math.pi) * N_LINKS)
        best = sectors.get(sector)
        if best is None or math.dist(d, CENTRE) > math.dist(best, CENTRE):
            sectors[sector] = d
    return [sectors[k] for k in sorted(sectors)]


def svg(dots: list[tuple[float, float]], linked: list[tuple[float, float]]) -> str:
    cx, cy = CENTRE
    parts = [
        f'<svg viewBox="0 0 {WIDTH} {HEIGHT}" aria-hidden="true" focusable="false">',
        "<defs>",
        f'<linearGradient id="signal-degrade" gradientUnits="userSpaceOnUse" x1="0" y1="0" x2="{WIDTH}" y2="{HEIGHT}">',
        f'<stop offset="0" stop-color="{CYAN}"/><stop offset="1" stop-color="{GREEN}"/>',
        "</linearGradient>",
        "</defs>",
    ]
    for i, (x, y) in enumerate(linked):
        parts.append(
            f'<line class="signal-lien" style="--d:{0.15 + i * 0.09:.2f}s" pathLength="1" '
            f'x1="{x:.1f}" y1="{y:.1f}" x2="{cx:.1f}" y2="{cy:.1f}" '
            'stroke="url(#signal-degrade)" stroke-width="2" stroke-linecap="round"/>'
        )
    linked_set = set(linked)
    for x, y in dots:
        if (x, y) in linked_set:
            parts.append(f'<circle cx="{x:.1f}" cy="{y:.1f}" r="6.5" fill="url(#signal-degrade)"/>')
        else:
            parts.append(f'<circle cx="{x:.1f}" cy="{y:.1f}" r="4.5" fill="{NEUTRAL}"/>')
    parts += [
        f'<circle class="signal-anneau" cx="{cx:.1f}" cy="{cy:.1f}" r="26" fill="none" stroke="{GREEN}" stroke-width="3"/>',
        f'<circle cx="{cx:.1f}" cy="{cy:.1f}" r="13" fill="url(#signal-degrade)" stroke="#ffffff" stroke-width="3"/>',
        (
            f'<text x="{cx + 24:.1f}" y="{cy - 22:.1f}" font-family="Atkinson Hyperlegible Mono Variable, monospace" '
            f'font-size="16" font-weight="700" fill="{INK}" stroke="#eef6fa" stroke-width="6" '
            'stroke-linejoin="round" paint-order="stroke">un signal</text>'
        ),
        "</svg>",
    ]
    return "\n".join(parts)


def main() -> None:
    rng = random.Random(SEED)
    dots = sample_dots(rng)
    linked = pick_linked(dots)
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(
        "<!-- Generated by tools/design/make_signal.py: edit the script, not this file. -->\n"
        "```{=html}\n" + svg(dots, linked) + "\n```\n",
        encoding="utf-8",
    )
    print(f"{OUT.relative_to(ROOT)} : {len(dots)} points, {len(linked)} liens.")


if __name__ == "__main__":
    main()
