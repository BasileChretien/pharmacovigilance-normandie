"""Draw the map of the departments of Normandy for normandie/carte.qmd.

The five departments, plain for the regional pharmacovigilance centre (CRPV) of Caen,
hatched for the CRPV of Rouen (the hatching tells them apart without colour), named,
with the two centres marked. Official outlines: Etalab, contours administratifs 2024
(from IGN Admin Express), Licence Ouverte / Open Licence 2.0, read from
data/normandie-carte.json (written by tools/design/fetch_normandie.py).

Writes assets/img/figures/carte-1.svg, a figure that follows docs/regles-redaction.md
section 5 and is placed in the page with the figure-svg shortcode. Deterministic: same
data, same file. Usage: python tools/design/make_carte_departements.py

Readable in the dark (docs/mode-sombre.md): the text colour comes from the page
(fill="currentColor"), the tint of the hatched departments is a shape under the hatching
(Dark Reader cannot measure a pattern's tile), and the legend swatches are wide enough for
Dark Reader to darken them like the map.
"""

from __future__ import annotations

import json
from collections.abc import Callable
from pathlib import Path

from fetch_normandie import simplify
from make_signal import make_projection

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "data" / "normandie-carte.json"
NAME = "carte-1"
OUT = ROOT / "assets" / "img" / "figures" / f"{NAME}.svg"

WIDTH, MAP_HEIGHT, MARGIN = 440, 330, 12
LEGEND_HEIGHT = 92
TOLERANCE = 0.8  # outline simplification, in figure units
FONT = "'Atkinson Hyperlegible Next Variable', system-ui, sans-serif"

# Design tokens of assets/theme.scss (checked by tools/checks/check_figures.py).
INK, PAPER, SIGNAL_DARK = "#10283a", "#ffffff", "#073f6e"
GREEN_INK, GREEN_TINT, MIST_DEEP = "#0b6b45", "#e6f7ef", "#dcebf3"
HATCH = f"url(#{NAME}-rayures)"
SWATCH_WIDTH = 48  # legend swatches: over 46 units, darkened like the map (check_figures.SMALL_SHAPE)
FILL = {"Caen": (MIST_DEEP, SIGNAL_DARK), "Rouen": (HATCH, GREEN_INK)}
# Label nudges, in figure units, where the centroid sits badly (thin or curved shapes)
# or under a centre's marker.
LABEL_SHIFT: dict[str, tuple[float, float]] = {"14": (0, 18), "76": (0, -6), "27": (6, 10), "50": (4, 6), "61": (0, 0)}
# Where each centre's name goes, relative to its dot: above for Caen, below for Rouen
# (above it, it would cover the name of Seine-Maritime).
CENTRE_LABEL_DY = {"Caen": -12.0, "Rouen": 26.0}

Point = tuple[float, float]


def _ring(ring: list[list[float]], project: Callable[[float, float], Point]) -> list[Point]:
    return [tuple(p) for p in simplify([list(project(lon, lat)) for lon, lat in ring], TOLERANCE)]


def _path(rings: list[list[Point]]) -> str:
    return " ".join("M" + " L".join(f"{x:.1f} {y:.1f}" for x, y in ring) + " Z" for ring in rings)


def area_and_centroid(ring: list[Point]) -> tuple[float, Point]:
    """Signed area and centroid of a closed polygon (shoelace formula)."""
    a = cx = cy = 0.0
    for (x1, y1), (x2, y2) in zip(ring, ring[1:] + ring[:1]):
        cross = x1 * y2 - x2 * y1
        a += cross
        cx += (x1 + x2) * cross
        cy += (y1 + y2) * cross
    a /= 2
    if a == 0:  # an islet simplified to a line: no area, no centroid of its own
        return 0.0, ring[0]
    return a, (cx / (6 * a), cy / (6 * a))


def _label(x: float, y: float, lines: list[tuple[str, bool]]) -> list[str]:
    """Centred label with a white halo, so that it reads over the fills and the borders."""
    out = []
    for i, (text, bold) in enumerate(lines):
        weight = ' font-weight="700"' if bold else ""
        out.append(
            f'<text x="{x:.1f}" y="{y + 20 * i:.1f}" text-anchor="middle"{weight} '
            f'stroke="{PAPER}" stroke-width="4" stroke-linejoin="round" paint-order="stroke">{text}</text>'
        )
    return out


def svg(data: dict) -> str:
    departements = data["departements"]
    project = make_projection(departements, WIDTH, MAP_HEIGHT, MARGIN)
    height = MAP_HEIGHT + LEGEND_HEIGHT
    parts = [
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {WIDTH} {height}" width="{WIDTH}" height="{height}" '
        f'font-family="{FONT}" font-size="16" fill="currentColor">',
        "  <!-- Generated by tools/design/make_carte_departements.py from data/normandie-carte.json: edit the script. -->",
        f'  <defs><pattern id="{NAME}-rayures" width="8" height="8" patternUnits="userSpaceOnUse" patternTransform="rotate(45)">'
        f'<path d="M0 0 V8" stroke="{GREEN_INK}" stroke-width="2"/></pattern></defs>',
    ]
    labels: list[str] = []
    for dep in departements:
        rings = [_ring(r, project) for r in dep["contours"]]
        fill, stroke = FILL[dep["crpv"]]
        if fill == HATCH:
            parts.append(f'  <path d="{_path(rings)}" fill="{GREEN_TINT}"/>')
        parts.append(
            f'  <path id="{NAME}-dep-{dep["code"]}" d="{_path(rings)}" fill="{fill}" '
            f'stroke="{stroke}" stroke-width="2" stroke-linejoin="round"/>'
        )
        _, (x, y) = max((area_and_centroid(r) for r in rings), key=lambda ac: abs(ac[0]))
        dx, dy = LABEL_SHIFT.get(dep["code"], (0, 0))
        labels += _label(x + dx, y + dy, [(dep["nom"], True), (f"({dep['code']})", False)])
    towns = {v["nom"]: v for v in data["villes"]}
    for centre in ("Caen", "Rouen"):
        x, y = project(towns[centre]["lon"], towns[centre]["lat"])
        labels.append(f'<circle cx="{x:.1f}" cy="{y:.1f}" r="6" fill="{INK}" stroke="{PAPER}" stroke-width="2"/>')
        labels += _label(x, y + CENTRE_LABEL_DY[centre], [(f"CRPV de {centre}", True)])
    parts += ["  " + p for p in labels]
    top = MAP_HEIGHT + 8
    parts += [
        f'  <rect x="16" y="{top}" width="{SWATCH_WIDTH}" height="22" fill="{MIST_DEEP}" stroke="{SIGNAL_DARK}" stroke-width="2"/>',
        f'  <text x="{SWATCH_WIDTH + 26}" y="{top + 17}"><tspan font-weight="700">CRPV de Caen</tspan> : Calvados, Manche, Orne</text>',
        f'  <rect x="16" y="{top + 32}" width="{SWATCH_WIDTH}" height="22" fill="{GREEN_TINT}"/>',
        f'  <rect x="16" y="{top + 32}" width="{SWATCH_WIDTH}" height="22" fill="{HATCH}" stroke="{GREEN_INK}" stroke-width="2"/>',
        f'  <text x="{SWATCH_WIDTH + 26}" y="{top + 49}"><tspan font-weight="700">CRPV de Rouen</tspan> : Eure, Seine-Maritime</text>',
        f'  <text x="16" y="{top + 76}" fill="#46586a">Contours : Etalab et IGN, Licence Ouverte.</text>',
        "</svg>",
    ]
    return "\n".join(parts) + "\n"


def main() -> None:
    data = json.loads(DATA.read_text(encoding="utf-8"))
    OUT.write_text(svg(data), encoding="utf-8")
    print(f"{OUT.relative_to(ROOT)} written")


if __name__ == "__main__":
    main()
