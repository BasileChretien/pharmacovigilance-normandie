"""Put the site's mascot in the Vigiking PDF masthead.

Writes bulletin/_extensions/vigiking/mascotte.typ: assets/img/mascotte.svg as a Typst string,
a template partial like reseau.typ (Typst reads no file outside the issue's folder). The
drawing lives in assets/img/mascotte.svg (docs/mascotte/README.md on the site): edit it
there, then run this script. Deterministic: same drawing, same file.

Usage: python tools/design/make_bulletin_mascotte.py
"""

from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "assets" / "img" / "mascotte.svg"
OUT = ROOT / "bulletin" / "_extensions" / "vigiking" / "mascotte.typ"


def compact(svg_text: str) -> str:
    """The drawing on one line, without its comments (the mascot has no text to keep)."""
    sans_notes = re.sub(r"<!--.*?-->", "", svg_text, flags=re.DOTALL)
    return re.sub(r">\s+<", "><", sans_notes).strip()


def typst(svg_text: str) -> str:
    """The SVG as a Typst string (no `$`: the file is also a Pandoc template partial)."""
    if "$" in svg_text:
        raise ValueError("mascotte.svg contains '$', which Pandoc templates would read")
    escaped = svg_text.replace("\\", "\\\\").replace('"', '\\"')
    return (
        "// Generated by tools/design/make_bulletin_mascotte.py from assets/img/mascotte.svg:"
        " edit the drawing, then run the script.\n"
        f'#let mascotte-svg = bytes("{escaped}")\n'
    )


def main() -> None:
    text = typst(compact(SOURCE.read_text(encoding="utf-8")))
    OUT.write_text(text, encoding="utf-8")
    print(f"{OUT.relative_to(ROOT)} : {len(text)} octets.")


if __name__ == "__main__":
    main()
