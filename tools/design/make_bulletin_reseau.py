"""Draw the bulletin's network map: the towns of Normandy, linked to the two CRPV.

The same figure as the home page (make_signal.py, same data and placement), drawn for
the bulletin's dark back cover and its generated cover: light lines on transparent,
no animation. Writes two files in bulletin/_extensions/vigiking/:

- reseau.svg, used by the web version;
- reseau.typ, the same SVG as a Typst string (a template partial: Typst reads no file
  outside the issue's folder, so the PDF gets the map inside its template).

Deterministic: same data, same figure.
Usage: python tools/design/make_bulletin_reseau.py
"""

from __future__ import annotations

import json
from collections.abc import Callable

from make_signal import (
    CRPV,
    DATA,
    HEIGHT,
    MARGIN,
    ROOT,
    WIDTH,
    _path,
    links,
    make_projection,
    select_towns,
)

OUT = ROOT / "bulletin" / "_extensions" / "vigiking"
CYAN, GREEN, ECUME, OR = "#19a6e3", "#2bcf8c", "#bfe3ee", "#e7b03b"

Point = tuple[float, float]


def _contours(data: dict, project: Callable[[float, float], Point]) -> list[str]:
    return [
        f'<path d="{_path(ring, project)}" fill="#ffffff" fill-opacity="0.05" '
        f'stroke="{ECUME}" stroke-opacity="0.35" stroke-width="1.2" stroke-linejoin="round"/>'
        for dep in data["departements"]
        for ring in dep["contours"]
    ]


def _liens(pairs: list[tuple[dict, dict]]) -> list[str]:
    return [
        f'<line x1="{t["x"]:.1f}" y1="{t["y"]:.1f}" x2="{h["x"]:.1f}" y2="{h["y"]:.1f}" '
        'stroke="url(#reseau-degrade)" stroke-opacity="0.8" stroke-width="1.4"/>'
        for t, h in pairs
    ]


def _villes(towns: list[dict], linked: set[str]) -> list[str]:
    parts = []
    for t in towns:
        if t["nom"] in CRPV.values():
            continue
        fill, opacity = (
            ("url(#reseau-degrade)", 1) if t["nom"] in linked else (ECUME, 0.45)
        )
        parts.append(
            f'<circle cx="{t["x"]:.1f}" cy="{t["y"]:.1f}" r="{t["r"]:.1f}" '
            f'fill="{fill}" fill-opacity="{opacity}"/>'
        )
    return parts


def _centres(hubs: list[dict]) -> list[str]:
    parts = []
    for h in hubs:
        x, y, r = h["x"], h["y"], h["r"]
        parts += [
            f'<circle cx="{x:.1f}" cy="{y:.1f}" r="{r + 7:.1f}" fill="none" stroke="{OR}" stroke-width="2.5"/>',
            f'<circle cx="{x:.1f}" cy="{y:.1f}" r="{r:.1f}" fill="#ffffff"/>',
        ]
    return parts


def svg(data: dict) -> str:
    project = make_projection(data["departements"], WIDTH, HEIGHT, MARGIN)
    towns = select_towns(data["villes"], project)
    pairs = links(towns)
    linked = {t["nom"] for t, _ in pairs}
    hubs = [t for t in towns if t["nom"] in CRPV.values()]
    return "".join(
        [
            f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {WIDTH} {HEIGHT}">',
            "<defs>",
            f'<linearGradient id="reseau-degrade" gradientUnits="userSpaceOnUse" x1="0" y1="0" x2="{WIDTH}" y2="{HEIGHT}">',
            f'<stop offset="0" stop-color="{CYAN}"/><stop offset="1" stop-color="{GREEN}"/>',
            "</linearGradient>",
            "</defs>",
            *_contours(data, project),
            *_liens(pairs),
            *_villes(towns, linked),
            *_centres(hubs),
            "</svg>",
        ]
    )


def typst(svg_text: str) -> str:
    """The SVG as a Typst string (no `$`: the file is also a Pandoc template partial)."""
    if "$" in svg_text:
        raise ValueError("reseau.svg contains '$', which Pandoc templates would read")
    escaped = svg_text.replace("\\", "\\\\").replace('"', '\\"')
    return (
        "// Generated by tools/design/make_bulletin_reseau.py: edit the script, not this file.\n"
        f'#let reseau-svg = bytes("{escaped}")\n'
    )


def main() -> None:
    data = json.loads(DATA.read_text(encoding="utf-8"))
    text = svg(data)
    (OUT / "reseau.svg").write_text(text + "\n", encoding="utf-8")
    (OUT / "reseau.typ").write_text(typst(text), encoding="utf-8")
    print(
        f"{(OUT / 'reseau.svg').relative_to(ROOT)} et reseau.typ : {len(text)} octets."
    )


if __name__ == "__main__":
    main()
