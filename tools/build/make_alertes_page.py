"""Write the lists of the official alerts feed (actualites/posts/alertes-officielles.qmd).

Reads data/alertes.json (written by tools/build/fetch_alertes.py) and writes one include
per source: _includes/alertes-ansm.md and _includes/alertes-ema.md. Every text comes from
the official sites and is escaped; each list says when and where it was read.
Standard library only: the weekly build runs it with the runner's python3.

Usage: python tools/build/make_alertes_page.py
"""

from __future__ import annotations

import html
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "data" / "alertes.json"
INCLUDES = ROOT / "_includes"
SITES = {
    "ansm": "le site de l'ANSM",
    "ema": "le site de l'Agence européenne des médicaments",
}
# EMA pages are in English: their titles and summaries are marked so screen readers switch.
LANGUE = {"ansm": None, "ema": "en"}


def _date(iso: str) -> str:
    year, month, day = iso.split("-")
    return f'<time datetime="{html.escape(iso)}">{day}/{month}/{year}</time>'


def _p(cls: str, content: str, lang: str | None = None) -> str:
    attr = f' lang="{lang}"' if lang else ""
    return f'<p class="{cls}"{attr}>{content}</p>'


def _item(alerte: dict, lang: str | None) -> str:
    meta = [_date(alerte["publie_le"])]
    if alerte.get("produit"):
        meta.append(html.escape(alerte["produit"]))
    if alerte.get("mis_a_jour_le"):
        meta.append("mis à jour le " + _date(alerte["mis_a_jour_le"]))
    parts = [
        _p("fil-meta", " · ".join(meta)),
        _p(
            "fil-titre",
            f'<a href="{html.escape(alerte["url"])}">{html.escape(alerte["titre"])}</a>',
            lang,
        ),
    ]
    if alerte.get("resume"):
        parts.append(_p("fil-resume", html.escape(alerte["resume"]), lang))
    if alerte.get("public"):
        parts.append(_p("fil-public", html.escape(alerte["public"])))
    return '<li class="fil-alerte">' + "".join(parts) + "</li>"


def liste(block: dict | None, key: str) -> str:
    """HTML of one source's list, preceded by the date and place it was read."""
    if not block:
        return _p(
            "fil-releve", f"Cette liste n'a pas encore été relevée sur {SITES[key]}."
        )
    releve = _p(
        "fil-releve",
        f"Liste relevée le {_date(block['releve_le'])} sur "
        f'<a href="{html.escape(block["source"])}">{SITES[key]}</a>.',
    )
    if not block["alertes"]:
        return releve + "\n" + _p("fil-releve", "Aucune communication relevée.")
    items = "\n".join(_item(a, LANGUE[key]) for a in block["alertes"])
    return releve + '\n<ul class="fil-alertes">\n' + items + "\n</ul>"


def main() -> None:
    data = json.loads(DATA.read_text(encoding="utf-8")) if DATA.exists() else {}
    INCLUDES.mkdir(exist_ok=True)
    for key in SITES:
        out = INCLUDES / f"alertes-{key}.md"
        out.write_text(
            "<!-- Generated by tools/build/make_alertes_page.py from data/alertes.json: "
            "edit the script, not this file. -->\n"
            "```{=html}\n" + liste(data.get(key), key) + "\n```\n",
            encoding="utf-8",
        )
        count = len((data.get(key) or {}).get("alertes", []))
        print(f"{out.relative_to(ROOT)} : {count} alertes.")


if __name__ == "__main__":
    main()
