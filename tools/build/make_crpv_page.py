"""Write the table of the regional pharmacovigilance centres for crpv/trouver-mon-crpv.qmd.

Reads data/crpv-france.json (written by tools/build/fetch_crpv.py) and writes
_includes/crpv-france.md: a JSON block read by assets/js/trouver-crpv.js, and the full
table of the centres, readable without JavaScript.
Usage: python tools/build/make_crpv_page.py
"""

from __future__ import annotations

import html
import json
from pathlib import Path
from urllib.parse import urlparse

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "data" / "crpv-france.json"
OUT = ROOT / "_includes" / "crpv-france.md"
NBSP = "\u00a0"
PARTIES = {
    "Nord": "partie nord",
    "Sud": "partie sud",
    "Est": "partie est",
    "Ouest": "partie ouest",
}


def _ordinal(n: int) -> str:
    return "1er" if n == 1 else f"{n}e"


def departements_label(centre: dict) -> str:
    parts = []
    for d in centre["departements"]:
        if d.get("arrondissements"):
            arr = ", ".join(_ordinal(n) for n in d["arrondissements"])
            parts.append(f"Paris ({arr} arrondissements)")
        elif d.get("precision"):
            parts.append(
                f"{d['nom']}, {PARTIES.get(d['precision'], d['precision'])} ({d['code']})"
            )
        else:
            parts.append(f"{d['nom']} ({d['code']})")
    return ", ".join(parts)


def _tel(telephone: str | None) -> str:
    if not telephone:
        return "&mdash;"
    digits = telephone.replace(" ", "")
    return (
        f'<a href="tel:+33{digits[1:]}">{html.escape(telephone.replace(" ", NBSP))}</a>'
    )


def _mail(courriel: str | None) -> str:
    if not courriel:
        return "&mdash;"
    return f'<a href="mailto:{html.escape(courriel)}">{html.escape(courriel)}</a>'


def _site(url: str | None) -> str:
    if not url:
        return "&mdash;"
    domain = urlparse(url).netloc.removeprefix("www.")
    return f'<a href="{html.escape(url)}">{html.escape(domain)}</a>'


def table(data: dict) -> str:
    rows = [
        (
            '<tr><th scope="col">Centre</th><th scope="col">Départements couverts</th>'
            '<th scope="col">Téléphone</th><th scope="col">Courriel</th><th scope="col">Site</th></tr>'
        )
    ]
    for c in data["centres"]:
        rows.append(
            f"<tr><td>{html.escape(c['nom'])}</td><td>{html.escape(departements_label(c))}</td>"
            f"<td>{_tel(c.get('telephone'))}</td><td>{_mail(c.get('courriel'))}</td><td>{_site(c.get('site'))}</td></tr>"
        )
    head, body = rows[0], rows[1:]
    return (
        '<table class="table crpv-table">\n<thead>'
        + head
        + "</thead>\n<tbody>\n"
        + "\n".join(body)
        + "\n</tbody>\n</table>"
    )


def data_block(data: dict) -> str:
    """JSON for the finder; '</' is escaped so a value can never close the script tag."""
    payload = json.dumps({"centres": data["centres"]}, ensure_ascii=False).replace(
        "</", "<\\/"
    )
    return f'<script type="application/json" id="crpv-donnees">{payload}</script>'


def main() -> None:
    data = json.loads(DATA.read_text(encoding="utf-8"))
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(
        "<!-- Generated by tools/build/make_crpv_page.py from data/crpv-france.json: "
        "edit the script, not this file. -->\n"
        "```{=html}\n" + data_block(data) + "\n" + table(data) + "\n```\n",
        encoding="utf-8",
    )
    print(f"{OUT.relative_to(ROOT)} : {len(data['centres'])} centres.")


if __name__ == "__main__":
    main()
