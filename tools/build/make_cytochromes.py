"""Build the cytochrome grid and the two-drug checker's data (bon-usage/cytochromes.qmd).

One hand-written source, data/cytochromes.yml (one entry per drug, as on the HUG card),
gives two generated files, so the grid and the checker always agree:
- _includes/cyp-grille.md: three tables in the HUG layout (substrates, inhibitors,
  inducers), one row per drug and one column per enzyme, strength written in words;
- _includes/cyp-donnees.md: the same data as JSON, read by assets/js/cyp-verificateur.js.
Usage: python tools/build/make_cytochromes.py
"""

from __future__ import annotations

import html
import json
import re
import sys
import unicodedata
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "data" / "cytochromes.yml"
PAGE = ROOT / "bon-usage" / "cytochromes.qmd"
OUT_GRID = ROOT / "_includes" / "cyp-grille.md"
OUT_DATA = ROOT / "_includes" / "cyp-donnees.md"

ENZYMES = ("CYP1A2", "CYP2B6", "CYP2C8", "CYP2C9", "CYP2C19", "CYP2D6", "CYP3A4/5", "P-gp")
ROLES = ("substrat", "inhibiteur", "inducteur")
VOIES = ("majeure", "mineure")
DRAPEAUX = {"prodrogue": "prodrogue", "métabolite-actif": "actif"}
FORCES = ("puissant", "modéré")
CLES = {"précision", *ROLES}

HEADER = "<!-- Generated by tools/build/make_cytochromes.py from data/cytochromes.yml: edit the data, not this file. -->\n"

TABLES = (
    ("substrat", "grille-substrats", "Substrats", "Tableau 1. Substrats : voie d'élimination majeure ou mineure "
     "du médicament par chaque enzyme, ou transport par la P-gp."),
    ("inhibiteur", "grille-inhibiteurs", "Inhibiteurs", "Tableau 2. Inhibiteurs puissants ou modérés de chaque "
     "enzyme ou de la P-gp."),
    ("inducteur", "grille-inducteurs", "Inducteurs", "Tableau 3. Inducteurs puissants ou modérés de chaque "
     "enzyme ou de la P-gp."),
)


def fold(text: str) -> str:
    """Lower case without accents, for sorting and for spotting duplicates."""
    return unicodedata.normalize("NFD", text).encode("ascii", "ignore").decode().lower()


def anchor(enzyme: str) -> str:
    """Id of the enzyme's Thésaurus examples on the page: exemples-cyp3a4-5, exemples-p-gp."""
    return "exemples-" + re.sub(r"[^a-z0-9]+", "-", enzyme.lower()).strip("-")


def _of(enzyme: str) -> str:
    """French article: "du CYP3A4/5", "de la P-gp"."""
    return "de la P-gp" if enzyme == "P-gp" else f"du {enzyme}"


def _fail(name: str, where: str, problem: str) -> None:
    raise ValueError(f"data/cytochromes.yml, {name}{where} : {problem}")


def _cell(name: str, role: str, enzyme: str, value: object, sources: dict, default: str) -> dict:
    """One cell of the card: 'mineure prodrogue', 'puissant thesaurus'…"""
    where = f" ({role}, {enzyme})"
    tokens = str(value).split()
    first, rest = (tokens[0] if tokens else ""), tokens[1:]
    allowed_first = VOIES if role == "substrat" else FORCES
    if first not in allowed_first:
        _fail(name, where, f"« {first} » inconnu, attendu : {' ou '.join(allowed_first)}")
    if role == "substrat":
        cell = {"voie": first, "prodrogue": False, "actif": False, "source": default}
    else:
        cell = {"force": first, "source": default}
    for token in rest:
        if role == "substrat" and token in DRAPEAUX:
            cell[DRAPEAUX[token]] = True
        elif token in sources:
            cell["source"] = token
        else:
            expected = ["prodrogue", "métabolite-actif"] if role == "substrat" else []
            _fail(name, where, f"« {token} » inconnu, attendu : {', '.join(expected + list(sources))}")
    return cell


def _drug(name: str, entry: object, sources: dict, default: str) -> dict:
    unknown = set(entry) - CLES if isinstance(entry, dict) else set()
    if unknown:
        _fail(name, "", f"clé inconnue : {', '.join(sorted(unknown))}")
    if not isinstance(entry, dict) or not any(entry.get(role) for role in ROLES):
        _fail(name, "", "aucun rôle (substrat, inhibiteur ou inducteur)")
    roles: dict[str, dict] = {}
    for role in ROLES:
        cells = entry.get(role) or {}
        if not isinstance(cells, dict):
            _fail(name, f" ({role})", "attendu : {ENZYME: valeur}")
        for enzyme, value in cells.items():
            if enzyme not in ENZYMES:
                _fail(name, f" ({role})", f"enzyme inconnue : {enzyme}, attendu : {', '.join(ENZYMES)}")
            roles.setdefault(enzyme, {})[role] = _cell(name, role, enzyme, value, sources, default)
    ordered = {e: {r: roles[e][r] for r in ROLES if r in roles[e]} for e in ENZYMES if e in roles}
    return {"nom": name[:1].upper() + name[1:], "precision": str(entry.get("précision") or ""), "roles": ordered}


def load(text: str) -> dict:
    """Read and check data/cytochromes.yml; drugs sorted alphabetically, ignoring accents."""
    raw = yaml.safe_load(text) or {}
    sources = raw.get("sources") or {}
    default = raw.get("source_par_defaut")
    if default not in sources:
        raise ValueError("data/cytochromes.yml : source_par_defaut doit être une clé de sources")
    seen: dict[str, str] = {}
    drugs = []
    for name, entry in (raw.get("medicaments") or {}).items():
        name = str(name)
        if fold(name) in seen:
            _fail(name, "", f"en double avec {seen[fold(name)]}")
        seen[fold(name)] = name
        drugs.append(_drug(name, entry, sources, default))
    drugs.sort(key=lambda d: fold(d["nom"]))
    return {"sources": sources, "source_par_defaut": default, "medicaments": drugs}


# ---------- Checker data --------------------------------------------------------


def to_checker_include(data: dict) -> str:
    payload = {
        "enzymes": [{"id": e, "de": _of(e), "ancre": anchor(e)} for e in ENZYMES],
        "sources": data["sources"],
        "source_par_defaut": data["source_par_defaut"],
        "medicaments": data["medicaments"],
    }
    # "<" escaped so that no value can close the script element.
    text = json.dumps(payload, ensure_ascii=False, separators=(",", ":")).replace("<", "\\u003c")
    return (HEADER + "\n```{=html}\n"
            f'<script type="application/json" id="cyp-donnees">{text}</script>\n```\n')


# ---------- Grid ----------------------------------------------------------------


def _label(role: str, cell: dict, sources: dict, default: str) -> str:
    if role == "substrat":
        strong, word = cell["voie"] == "majeure", cell["voie"].capitalize()
    else:
        strong, word = cell["force"] == "puissant", cell["force"].capitalize()
    parts = [f'<span class="cyp-marque">{html.escape(word)}</span>']
    if cell.get("prodrogue"):
        parts.append('<span class="cyp-drapeau">prodrogue</span>')
    if cell.get("actif"):
        parts.append('<span class="cyp-drapeau">métabolite actif</span>')
    if cell["source"] != default:
        parts.append(f'<span class="cyp-source">({html.escape(sources[cell["source"]]["court"])})</span>')
    css = "cyp-fort" if strong else "cyp-moyen"
    return f'<td class="{css}">' + " ".join(parts) + "</td>"


def _row(drug: dict, role: str, sources: dict, default: str) -> str:
    name = html.escape(drug["nom"])
    if drug["precision"]:
        name += f' <span class="cyp-precision">({html.escape(drug["precision"])})</span>'
    cells = []
    for enzyme in ENZYMES:
        cell = drug["roles"].get(enzyme, {}).get(role)
        cells.append(_label(role, cell, sources, default) if cell else "<td></td>")
    return f'<tr><th scope="row">{name}</th>' + "".join(cells) + "</tr>"


def _table(data: dict, role: str, caption: str, title: str, number: int) -> str:
    sources, default = data["sources"], data["source_par_defaut"]
    heads = "".join(f'<th scope="col">{html.escape(e)}</th>' for e in ENZYMES)
    rows = [_row(d, role, sources, default) for d in data["medicaments"]
            if any(role in r for r in d["roles"].values())]
    return "\n".join([
        f'<div class="cyp-grille-cadre" role="region" aria-label="Tableau {number} : {title.lower()}" tabindex="0">',
        '<table class="cyp-grille">',
        f"<caption>{html.escape(caption)}</caption>",
        f'<thead><tr><th scope="col">Médicament</th>{heads}</tr></thead>',
        "<tbody>",
        *rows,
        "</tbody>",
        "</table>",
        "</div>",
    ])


def to_grid(data: dict) -> str:
    parts = [HEADER]
    for number, (role, ident, title, caption) in enumerate(TABLES, start=1):
        parts.append(f"### {title} {{#{ident}}}\n")
        parts.append("```{=html}\n" + _table(data, role, caption, title, number) + "\n```\n")
    return "\n".join(parts)


def main() -> int:
    try:
        data = load(SOURCE.read_text(encoding="utf-8"))
    except ValueError as error:
        print(error, file=sys.stderr)
        return 1
    OUT_GRID.parent.mkdir(exist_ok=True)
    OUT_GRID.write_text(to_grid(data), encoding="utf-8")
    OUT_DATA.write_text(to_checker_include(data), encoding="utf-8")
    count = len(data["medicaments"])
    print(f"{OUT_GRID.relative_to(ROOT)}, {OUT_DATA.relative_to(ROOT)} : {count} médicaments.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
