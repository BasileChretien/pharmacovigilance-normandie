"""Write the list of recent publications of crpv/recherche.qmd.

Reads data/publications.json (written by tools/build/fetch_publications.py) and writes
_includes/publications.md: newest first, each work's title linked to its DOI, its year,
its journal, its team, and free access or retraction when OpenAlex reports them. No
author names: only the members whose card is on the team pages agreed to be named, and
the DOI leads to the full reference. Every text is escaped. Standard library only: the
build runs it with the runner's python3.

Usage: python tools/build/make_publications_page.py
"""

from __future__ import annotations

import html
import json
from pathlib import Path
from urllib.parse import quote, unquote

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "data" / "publications.json"
OUT = ROOT / "_includes" / "publications.md"
SOURCES = '<a href="https://orcid.org/">ORCID</a> et <a href="https://openalex.org/">OpenAlex</a>'
EQUIPES = {"caen": "Caen", "rouen": "Rouen"}
# The mascot in the list's empty states (docs/mascotte/README.md), decorative. The path is
# relative to crpv/recherche.qmd, the only page that includes this list.
MASCOTTE = (
    '<img class="mascotte" src="../assets/img/mascotte.svg" alt="" aria-hidden="true" '
    'width="60" height="70">'
)


def _p(cls: str, content: str, lang: str | None = None) -> str:
    attr = f' lang="{lang}"' if lang else ""
    return f'<p class="{cls}"{attr}>{content}</p>'


def _vide(content: str) -> str:
    """An empty state: the mascot beside its message."""
    return f'<div class="etat-vide">{MASCOTTE}{content}</div>'


def _date(iso: str) -> str:
    year, month, day = iso.split("-")
    return f'<time datetime="{html.escape(iso)}">{day}/{month}/{year}</time>'


def _equipes(cles: list[str]) -> str:
    noms = [EQUIPES[c] for c in cles if c in EQUIPES]
    if len(noms) > 1:
        return "Équipes de " + " et de ".join(noms)
    return f"Équipe de {noms[0]}" if noms else ""


def _lien_doi(doi: str) -> str:
    """The DOI's address, percent-encoded: a #, ? or % in a DOI would break the link."""
    return "https://doi.org/" + quote(doi, safe="/:;()")


def _item(p: dict) -> str:
    annee = html.escape(p["publie_le"][:4])
    meta = [f'<time datetime="{annee}">{annee}</time>']
    if p.get("revue"):
        meta.append(f"<em>{html.escape(p['revue'])}</em>")
    lien = f'<a href="{html.escape(_lien_doi(p["doi"]))}">{html.escape(p["titre"])}</a>'
    langue = p.get("langue") if p.get("langue") not in (None, "fr") else None
    parts = [_p("fil-meta", " · ".join(meta)), _p("fil-titre", lien, langue)]
    details = [_equipes(p.get("equipes") or [])]
    libre = p.get("acces_libre")
    if libre and unquote(libre).lower().rstrip("/") == f"https://doi.org/{p['doi']}":
        details.append("en accès libre")  # the title's link already leads there
    elif libre:
        details.append(
            f'<a href="{html.escape(libre)}">texte intégral en accès libre</a>'
        )
    if p.get("retracte"):
        details.append("<strong>article rétracté</strong> par la revue")
    parts.append(_p("fil-public", " · ".join(d for d in details if d)))
    return '<li class="fil-alerte">' + "".join(parts) + "</li>"


def liste(data: dict | None) -> str:
    """HTML of the list, preceded by the date and sources it was read from."""
    data = data or {}
    if not data.get("membres"):
        return _vide(
            _p(
                "fil-releve",
                "La liste se remplira d'elle-même quand des membres des équipes auront "
                "publié leur carte, avec leur accord écrit et leur identifiant ORCID.",
            )
        )
    non_lus = set(data.get("non_lus") or [])
    if not data.get("releve_le") or non_lus >= set(data["membres"]):
        return _vide(
            _p(
                "fil-releve",
                f"Cette liste n'a pas encore pu être relevée sur {SOURCES}.",
            )
        )
    releve = _p(
        "fil-releve",
        f"Liste relevée le {_date(data['releve_le'])} sur {SOURCES} : publications depuis "
        f"{data['depuis']} des membres dont la carte figure sur les pages des équipes. Le "
        "lien de chaque titre donne la référence complète.",
    )
    if non_lus:
        qui = "d'un membre" if len(non_lus) == 1 else f"de {len(non_lus)} membres"
        releve += "\n" + _p(
            "fil-releve",
            f"Les publications {qui} n'ont pas pu être relevées : elles manquent à cette "
            "liste.",
        )
    if not data["publications"]:
        return releve + "\n" + _vide(_p("fil-releve", "Aucune publication relevée."))
    items = "\n".join(_item(p) for p in data["publications"])
    return releve + '\n<ul class="fil-alertes">\n' + items + "\n</ul>"


def main() -> None:
    try:
        data = json.loads(DATA.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        data = None
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(
        "<!-- Generated by tools/build/make_publications_page.py from data/publications.json: "
        "edit the script, not this file. -->\n"
        "```{=html}\n" + liste(data) + "\n```\n",
        encoding="utf-8",
    )
    count = len((data or {}).get("publications") or [])
    print(f"{OUT.relative_to(ROOT)} : {count} publications.")


if __name__ == "__main__":
    main()
