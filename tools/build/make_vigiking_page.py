"""Write the archive table of vigiking/archives.qmd from data/vigiking-archives.json
(written by tools/build/fetch_vigiking.py): one row per issue, its topics as the network
lists them, a link to its page and to its PDF on rfcrpv.fr. The page wraps the table in
the site's filter (assets/js/table-filter.js), so readers find issues by topic.

Usage: python tools/build/make_vigiking_page.py
"""

from __future__ import annotations

import html
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "data" / "vigiking-archives.json"
INCLUDES = ROOT / "_includes"
MOIS = [
    "janvier",
    "février",
    "mars",
    "avril",
    "mai",
    "juin",
    "juillet",
    "août",
    "septembre",
    "octobre",
    "novembre",
    "décembre",
]


def _de(titre: str) -> str:
    """'Avril 2025' -> 'd’avril 2025'; 'Mai 2024' -> 'de mai 2024'. No elision before "h"
    (h aspiré: 'de hors-série')."""
    t = titre.lower()
    return ("d’" if t[:1] in "aeiouéèêàâîïôû" else "de ") + t


def _mois(iso: str | None) -> str:
    if not iso:
        return "?"
    annee, mois = iso.split("-")
    return f"{MOIS[int(mois) - 1]} {annee}"


def table(data: dict) -> str:
    rows = [
        '<tr><th scope="col">Numéro</th><th scope="col">Sujets</th><th scope="col">PDF</th></tr>'
    ]
    for n in data["numeros"]:
        titre = html.escape(n["titre"])
        if n["sujets"]:
            sujets = (
                "<ul>"
                + "".join(f"<li>{html.escape(s)}</li>" for s in n["sujets"])
                + "</ul>"
            )
        else:
            sujets = '<span class="vigiking-sans-sommaire">Sommaire non indiqué sur le site du réseau</span>'
        rows.append(
            f'<tr><td><a href="{html.escape(n["page"])}">{titre}</a></td><td>{sujets}</td>'
            f'<td><a href="{html.escape(n["pdf"])}">PDF<span class="visually-hidden"> '
            f"{html.escape(_de(n['titre']))}</span></a></td></tr>"
        )
    head, body = rows[0], rows[1:]
    return (
        '<table class="table vigiking-table">\n<thead>'
        + head
        + "</thead>\n<tbody>\n"
        + "\n".join(body)
        + "\n</tbody>\n</table>"
    )


def releve(data: dict) -> str:
    """When and where the list was read, with the number of issues and their span."""
    annee, mois, jour = data["consulte_le"].split("-")
    mois_lus = sorted(n["mois"] for n in data["numeros"] if n["mois"])
    etendue = f", de {_mois(mois_lus[0])} à {_mois(mois_lus[-1])}" if mois_lus else ""
    return (
        f'<p class="vigiking-releve">Liste relevée le {jour}/{mois}/{annee} sur '
        f'<a href="{html.escape(data["source"])}">le site du réseau des CRPV</a> : '
        f"{len(data['numeros'])} numéros{etendue}.</p>"
    )


def _include(nom: str, contenu: str) -> None:
    (INCLUDES / f"vigiking-{nom}.md").write_text(
        "<!-- Generated by tools/build/make_vigiking_page.py from data/vigiking-archives.json: "
        "edit the script, not this file. -->\n```{=html}\n" + contenu + "\n```\n",
        encoding="utf-8",
    )


def main() -> None:
    data = json.loads(DATA.read_text(encoding="utf-8"))
    _include("releve", releve(data))
    _include("archives", table(data))
    print(f"_includes/vigiking-archives.md : {len(data['numeros'])} numéros.")


if __name__ == "__main__":
    main()
