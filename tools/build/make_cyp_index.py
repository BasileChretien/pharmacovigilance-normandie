"""Build the per-drug index of the cytochrome table (bon-usage/cytochromes.qmd).

Reads the table organised by enzyme and writes _includes/cyp-index.md: one row per
drug, with its role for each enzyme (substrate, strong or moderate inhibitor,
inducer). The index is generated from the table, so the two always agree.
Usage: python tools/build/make_cyp_index.py
"""

from __future__ import annotations

import re
import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "bon-usage" / "cytochromes.qmd"
OUT = ROOT / "_includes" / "cyp-index.md"

_LABEL = re.compile(r"^(puissants?|modérés?|faibles?|prodrogues?)\s*:\s*", re.IGNORECASE)
_STRENGTH = {"puissant": "puissant", "puissants": "puissant", "modéré": "modéré", "modérés": "modéré",
             "faible": "faible", "faibles": "faible"}


def parse_table(markdown: str) -> list[dict[str, str]]:
    """Rows of the enzyme table: enzyme, substrats, inhibiteurs, inducteurs."""
    rows = []
    for line in markdown.splitlines():
        if not line.startswith("| **"):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) < 4:
            continue
        rows.append({
            "enzyme": cells[0].strip("* "),
            "substrats": cells[1],
            "inhibiteurs": cells[2],
            "inducteurs": cells[3],
        })
    return rows


def split_cell(cell: str) -> list[tuple[str, str]]:
    """Drug names of a cell, each with the strength label that precedes it ('' if none)."""
    text = re.sub(r"\([^)]*\)", "", cell)          # explanations in brackets
    text = text.replace("(!)", "").replace("*", "")
    entries: list[tuple[str, str]] = []
    for sentence in re.split(r"[.;]\s*", text):
        strength = ""
        sentence = sentence.strip()
        label = _LABEL.match(sentence)
        if label:
            strength = _STRENGTH.get(label.group(1).lower(), "")
            sentence = sentence[label.end():]
        for name in re.split(r",|\s+et\s+", sentence):
            name = name.strip(" !:").strip()
            if name and len(name) > 2 and not name[0].isdigit():
                entries.append((name[0].lower() + name[1:], strength))
    return entries


def _of(enzyme: str) -> str:
    """French article: "du CYP3A4", "de la P-glycoprotéine"."""
    return f"de la {enzyme}" if enzyme.lower().startswith("p-glyco") else f"du {enzyme}"


def build_index(rows: list[dict[str, str]]) -> dict[str, list[str]]:
    index: dict[str, list[str]] = {}
    for row in rows:
        enzyme = row["enzyme"]
        for name, _ in split_cell(row["substrats"]):
            index.setdefault(name, []).append(f"substrat {_of(enzyme)}")
        for kind, column in (("inhibiteur", "inhibiteurs"), ("inducteur", "inducteurs")):
            for name, strength in split_cell(row[column]):
                role = f"{kind} {strength} {_of(enzyme)}".replace("  ", " ")
                index.setdefault(name, []).append(role)
    return {name: list(dict.fromkeys(roles)) for name, roles in index.items()}


def _sort_key(name: str) -> str:
    return unicodedata.normalize("NFD", name).encode("ascii", "ignore").decode().lower()


def to_markdown(index: dict[str, list[str]]) -> str:
    lines = [
        "<!-- Generated by tools/build/make_cyp_index.py from the table above: edit the table, not this file. -->",
        "",
        "| Médicament | Rôle dans le tableau |",
        "|---|---|",
    ]
    for name in sorted(index, key=_sort_key):
        lines.append(f"| {name[0].upper() + name[1:]} | {' ; '.join(index[name])} |")
    return "\n".join(lines) + "\n"


def main() -> int:
    rows = parse_table(SOURCE.read_text(encoding="utf-8"))
    if not rows:
        print("Aucune ligne d'enzyme trouvée dans le tableau.", file=sys.stderr)
        return 1
    index = build_index(rows)
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(to_markdown(index), encoding="utf-8")
    print(f"{OUT.relative_to(ROOT)} : {len(index)} médicaments, {len(rows)} enzymes.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
