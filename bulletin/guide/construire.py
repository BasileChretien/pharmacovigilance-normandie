"""Build the authors' guide from bulletin/guide/source.html.

- bulletin/guide/index.html: the repository copy, a full HTML page that reads the
  bulletin's own fonts (_extensions/vigiking/fonts/) and links the Word template next to it.
- With --en-ligne DOSSIER: DOSSIER/index.html, the page published online, its fonts
  embedded and its links absolute (the publishing tool adds the HTML skeleton).

Both get French spacing: no line break before « : ; ? ! » or after « « ».

Usage: python bulletin/guide/construire.py [--en-ligne DOSSIER]
"""

from __future__ import annotations

import argparse
import base64
import re
from pathlib import Path

ICI = Path(__file__).resolve().parent
DEPOT = ICI.parents[1]
POLICES = DEPOT / "assets" / "fonts"
# Download links: the bulletin's branch on GitHub until it is merged (then: main).
DEPOT_GITHUB = "BasileChretien/pharmacovigilance-normandie"
BRANCHE = "feat/bulletin-prototype"
ZIP = f"https://github.com/{DEPOT_GITHUB}/archive/refs/heads/{BRANCHE}.zip"
MODELE_EN_LIGNE = f"https://raw.githubusercontent.com/{DEPOT_GITHUB}/{BRANCHE}/bulletin/word/modele-vigiking.docx"
MODELE_LOCAL = "../word/modele-vigiking.docx"
POLICES_EN_LIGNE = {
    "__ATKINSON__": "atkinson-hyperlegible-next-latin-wght-normal.woff2",
    "__BRICOLAGE__": "bricolage-grotesque-latin-wght-normal.woff2",
    "__MONO__": "atkinson-hyperlegible-mono-latin-wght-normal.woff2",
}
POLICES_LOCALES = (
    '@font-face { font-family: "Atkinson Hyperlegible Next"; font-weight: 200 800; font-display: swap; '
    'src: url("../_extensions/vigiking/fonts/atkinson-hyperlegible-next-latin-wght-normal.woff2") format("woff2"); }\n'
    '@font-face { font-family: "Bricolage Grotesque"; font-weight: 200 800; font-display: swap; '
    'src: url("../_extensions/vigiking/fonts/bricolage-grotesque-latin-wght-normal.woff2") format("woff2"); }\n'
    "img { max-width: 100%; }"
)
ENTETE = (
    '<!DOCTYPE html>\n<html lang="fr">\n<head>\n<meta charset="utf-8">\n'
    '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">\n'
    "<!-- Generated by bulletin/guide/construire.py from source.html: edit the source. -->\n"
)


def espaces_insecables(html: str) -> str:
    """French spacing in the text only: tags, CSS, code samples (the author types them)
    and the console replicas are left as they are."""
    morceaux = re.split(r"(<[^>]+>)", html)
    garde = 0
    for i, m in enumerate(morceaux):
        if m.startswith("<"):
            nom = re.match(r"</?([a-zA-Z]+)", m)
            if nom and nom[1].lower() in ("style", "code", "pre", "kbd"):
                garde += -1 if m.startswith("</") else 1
            continue
        if garde == 0:
            m = re.sub(r" ([:;?!»])", lambda t: " " + t[1], m)
            morceaux[i] = m.replace("« ", "« ")
    return "".join(morceaux)


def source() -> str:
    texte = (ICI / "source.html").read_text(encoding="utf-8")
    return espaces_insecables(texte).replace("__ZIP__", ZIP)


def page_locale(texte: str) -> str:
    """The repository copy: a full page, the bulletin's fonts, the template next to it."""
    lignes = [
        ligne
        for ligne in texte.replace("__MODELE__", MODELE_LOCAL).splitlines()
        if not ligne.startswith("@font-face")
        and "claude:viewport-fit-sides" not in ligne
    ]
    corps = "\n".join(lignes).replace(
        "<style>\n", "<style>\n" + POLICES_LOCALES + "\n", 1
    )
    titre, reste = corps.split("\n", 1)
    page = (
        ENTETE
        + titre
        + "\n"
        + reste.replace(
            '\n<header class="une">', '\n</head>\n<body>\n<header class="une">', 1
        )
        + "\n</body>\n</html>\n"
    )
    if page.count("<style>") != 1 or "</head>" not in page:
        raise SystemExit("construire : source.html n'a pas la forme attendue.")
    return page


def page_en_ligne(texte: str) -> str:
    """The online page: fonts embedded, links absolute."""
    texte = texte.replace("__MODELE__", MODELE_EN_LIGNE)
    for cle, fichier in POLICES_EN_LIGNE.items():
        texte = texte.replace(
            cle, base64.b64encode((POLICES / fichier).read_bytes()).decode()
        )
    return texte


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--en-ligne", type=Path, help="dossier de la version publiée en ligne"
    )
    args = parser.parse_args()
    texte = source()
    (ICI / "index.html").write_text(page_locale(texte), encoding="utf-8")
    print("bulletin/guide/index.html écrit.")
    if args.en_ligne:
        args.en_ligne.mkdir(parents=True, exist_ok=True)
        (args.en_ligne / "index.html").write_text(
            page_en_ligne(texte), encoding="utf-8"
        )
        print(f"{args.en_ligne / 'index.html'} écrit.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
